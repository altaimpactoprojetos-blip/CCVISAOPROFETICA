-- Acessos da recepção (validam inscrições na entrada) e registro da validação.
alter table public.admin_credentials add column if not exists role text not null default 'admin';
alter table public.admin_credentials add column if not exists display_name text;
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'admin_credentials_role_check') then
    alter table public.admin_credentials add constraint admin_credentials_role_check check (role in ('admin', 'recepcao'));
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'admin_credentials' and column_name = 'id' and is_identity = 'YES') then
    alter table public.admin_credentials alter column id add generated by default as identity (start with 100);
  end if;
end $$;

